-- Create public.aka_lab_result table linking lab results with opd registration and patient details.
-- Run this in your Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.aka_lab_result (
  lab_result_id bigint generated by default as identity not null,
  registration_id bigint not null,
  patient_uhid text not null,
  name text not null,
  unit text null,
  reading text null,
  interpretation text null,
  result_date text null, -- Represents observation date (formatted as text, e.g. "11 Jul 26")
  notes text null,
  created_date date not null default (timezone('Asia/Kolkata'::text, now()))::date, -- Current India Date
  constraint aka_lab_result_pkey primary key (lab_result_id),
  constraint aka_lab_result_registration_id_fkey foreign key (registration_id) references public.aka_opd_registration (registration_id) on delete cascade,
  constraint aka_lab_result_patient_uhid_fkey foreign key (patient_uhid) references public.patient_detail (uhid) on delete cascade
) TABLESPACE pg_default;

-- Create index for faster lookups
CREATE INDEX IF NOT EXISTS idx_aka_lab_result_registration ON public.aka_lab_result (registration_id);
CREATE INDEX IF NOT EXISTS idx_aka_lab_result_patient_uhid ON public.aka_lab_result (patient_uhid);
